#!/usr/bin/env python3
"""Generate a SYNTHETIC dataset with the same schema as `lab.py collect`.

Purpose: exercise and demo the analysis pipeline (and run the unit tests)
without spending any CI minutes. The numbers it yields are a consequence of
the generator's assumptions and must never be reported as experimental results.
"""
from __future__ import annotations

import argparse
import json
import random
from datetime import datetime, timedelta, timezone
from pathlib import Path

import plan as planlib

FMT = "%Y-%m-%dT%H:%M:%SZ"
START = datetime(2026, 1, 5, 9, 0, 0, tzinfo=timezone.utc)


def _ts(dt):
    return dt.strftime(FMT)


def generate(pairs=12, seed=42, build_seconds=120, jitter=30, setup_seconds=35, fail_prob=0.03):
    rng = random.Random(seed)
    items = planlib.make_plan(pairs, seed)
    clock = START
    run_id, pr_number = 10_000, 0
    prs, runs, manifest_prs = [], [], []

    def add_run(branch, executed, at):
        nonlocal run_id
        run_id += 1
        queue = rng.randint(2, 20)
        if executed:
            duration = max(10, build_seconds + rng.uniform(-jitter, jitter) + setup_seconds)
            started = at + timedelta(seconds=queue)
            completed = started + timedelta(seconds=duration)
            conclusion = "failure" if rng.random() < fail_prob else "success"
            jobs = [{"name": "build", "conclusion": conclusion,
                     "started_at": _ts(started), "completed_at": _ts(completed)}]
            updated = completed
        else:
            started, updated, conclusion, jobs = at, at + timedelta(seconds=2), "skipped", []
        runs.append({"databaseId": run_id, "headBranch": branch, "headSha": f"{run_id:040x}",
                     "status": "completed", "conclusion": conclusion, "createdAt": _ts(at),
                     "startedAt": _ts(started), "updatedAt": _ts(updated),
                     "event": "pull_request", "attempt": 1, "jobs": jobs})

    for item in items:
        for arm in planlib.arm_order(item.pair_id, seed):
            branch, created = item.branch(arm), clock
            # event sequence: True = executed run, False = skipped run
            if arm == "ctrl":
                events = [True] * item.total_pushes
            else:
                events = [False] * item.wip_commits + [True]
                for commits in item.review_rounds:
                    events += [False] * commits + [True]
            for executed in events:
                clock += timedelta(seconds=rng.randint(60, 600))
                add_run(branch, executed, clock)
            clock += timedelta(seconds=rng.randint(300, 1800))
            pr_number += 1
            prs.append({"number": pr_number, "title": f"[LAB] {item.title()}", "headRefName": branch,
                        "isDraft": False, "state": "MERGED", "createdAt": _ts(created),
                        "mergedAt": _ts(clock), "closedAt": _ts(clock)})
            e, s = item.expected_runs(arm)
            manifest_prs.append({"pair_id": item.pair_id, "task": item.task, "arm": arm,
                                 "branch": branch, "pr_number": pr_number, "pushes": item.total_pushes,
                                 "expected_executed": e, "expected_skipped": s})
    meta = {"repo": "example/draft-pr-lab", "collected_at": _ts(clock), "synthetic": True,
            "generator": "tools/make_synthetic_data.py", "seed": seed}
    manifest = {"seed": seed, "pairs": pairs, "repo": meta["repo"], "prs": manifest_prs}
    return prs, runs, meta, manifest


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default="data/synthetic")
    ap.add_argument("--pairs", type=int, default=12)
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args(argv)
    prs, runs, meta, manifest = generate(args.pairs, args.seed)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "prs.json").write_text(json.dumps(prs, indent=2))
    (out / "runs.json").write_text(json.dumps(runs, indent=2))
    (out / "meta.json").write_text(json.dumps(meta, indent=2))
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2))
    (out / "README.md").write_text(
        "# SYNTHETIC DATA\n\nGenerated by `tools/make_synthetic_data.py` to exercise the analysis "
        "pipeline. Not experimental data; never cite these numbers as results.\n")
    print(f"Wrote {len(prs)} PRs and {len(runs)} runs to {out}/")


if __name__ == "__main__":
    main()
